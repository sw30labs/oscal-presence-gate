"""Evidence emitter.

Turns each gate decision into an OSCAL assessment-results observation with
the raw decision record embedded, so the audit trail writes itself while the
control runs. Mirrors the oscal-skills-guardrails evidence stream — the two
sets can sit in one audit package.
"""
from __future__ import annotations

import json
import uuid
from datetime import timezone
from pathlib import Path
from typing import Any, Optional

from .models import Decision, utcnow

OSCAL_VERSION = "1.1.3"


def _iso(dt) -> str:
    return dt.astimezone(timezone.utc).isoformat(timespec="seconds")


def _reviewed_controls(decisions: list[Decision]) -> dict[str, Any]:
    # reviewed means reviewed — list the controls this batch actually exercised
    control_ids = sorted({cid for d in decisions for cid in d.control_ids})
    if not control_ids:
        return {"control-selections": [{"include-all": {}}]}
    return {
        "description": "Controls exercised by the decisions in this batch.",
        "control-selections": [
            {"include-controls": [{"control-id": cid} for cid in control_ids]}
        ],
    }


def build_assessment_results(
    decisions: list[Decision],
    title: str = "oscal-presence-gate runtime decisions",
    import_ap_href: str = "./assessment-plan-placeholder.json",
) -> dict[str, Any]:
    now = utcnow()
    observations = []
    for d in decisions:
        observations.append(
            {
                "uuid": str(uuid.uuid4()),
                "title": f"{d.effect.upper()} — {d.tool_name} for {d.principal}",
                "description": (
                    f"Presence-gate decision '{d.effect}' for tool '{d.tool_name}' "
                    f"(principal {d.principal}, presence {d.presence_status}, "
                    f"country {d.country or 'unknown'}). Controls: {', '.join(d.control_ids) or 'n/a'}."
                ),
                "methods": ["TEST"],
                "collected": _iso(d.timestamp),
                "relevant-evidence": [
                    {
                        "description": "Structured decision record (PRES-5 custody log): "
                        + json.dumps(d.to_record(), sort_keys=True)
                    }
                ],
            }
        )

    return {
        "assessment-results": {
            "uuid": str(uuid.uuid4()),
            "metadata": {
                "title": title,
                "last-modified": _iso(now),
                "version": "0.1.0",
                "oscal-version": OSCAL_VERSION,
                "remarks": (
                    "Generated by oscal-presence-gate evidence_emitter. Each observation embeds "
                    "the runtime decision record it evidences. Retention obligation: see "
                    "pres_prm_log_retention (aligned with CISA twelve-month central logging)."
                ),
            },
            "import-ap": {
                "href": import_ap_href,
                # TODO(nic): v0.3 ships a real minimal assessment plan — retire this placeholder
                "remarks": "Placeholder — v0.3 ships a minimal assessment plan for the PRES controls.",
            },
            "results": [
                {
                    "uuid": str(uuid.uuid4()),
                    "title": "Presence-gate decision batch",
                    "description": f"{len(decisions)} gate decision(s) captured as observations.",
                    "start": _iso(min((d.timestamp for d in decisions), default=now)),
                    "end": _iso(max((d.timestamp for d in decisions), default=now)),
                    "reviewed-controls": _reviewed_controls(decisions),
                    "observations": observations,
                }
            ],
        }
    }


def emit(
    decisions: list[Decision],
    out_path: Optional[Path] = None,
    **kwargs: Any,
) -> dict[str, Any]:
    doc = build_assessment_results(decisions, **kwargs)
    if out_path is not None:
        out_path = Path(out_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(doc, f, indent=2)
    return doc
